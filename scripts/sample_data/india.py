"""SALES_002: generated Indian sales data (INR, day/month/year, lakh/crore) with planted stories."""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from .common import COLUMNS, make_messy, write_outputs

DATASET_ID = "SALES_002"
LOCALE = "en_IN"
SEED = 2002
N_ORDERS = 400
START, END = "2025-01-01", "2026-06-30"
FESTIVE_MONTHS = (10, 11)            # Diwali season: more orders
FESTIVE_WEIGHT = 1.6
DROP = {"region": "North", "category": "Electronics", "month": "2026-03", "share_removed": 0.30}
RETURN_RATE = 0.02

# (product, category, sub_category, unit price in INR, typical margin)
PRODUCTS = [
    ("Laptop", "Electronics", "Computers", 55000, 0.12),
    ("Smartphone", "Electronics", "Phones", 22000, 0.10),
    ("Headphones", "Electronics", "Accessories", 2500, 0.25),
    ("Monitor", "Electronics", "Computers", 12000, 0.15),
    ("Printer", "Electronics", "Machines", 9000, 0.18),
    ("Office Chair", "Furniture", "Chairs", 7500, 0.20),
    ("Study Table", "Furniture", "Tables", 11000, 0.18),
    ("Bookshelf", "Furniture", "Storage", 6000, 0.22),
    ("Sofa", "Furniture", "Seating", 35000, 0.15),
    ("Filing Cabinet", "Furniture", "Storage", 8500, 0.20),
    ("Notebook Pack", "Office Supplies", "Paper", 250, 0.35),
    ("Pen Set", "Office Supplies", "Writing", 150, 0.40),
    ("Stapler", "Office Supplies", "Tools", 300, 0.30),
    ("Paper Ream", "Office Supplies", "Paper", 400, 0.25),
    ("Desk Organizer", "Office Supplies", "Storage", 650, 0.30),
]
REGIONS = {
    "North": ["Delhi", "Punjab", "Uttar Pradesh"],
    "South": ["Karnataka", "Tamil Nadu", "Kerala"],
    "East": ["West Bengal", "Odisha", "Bihar"],
    "West": ["Maharashtra", "Gujarat", "Rajasthan"],
    "Central": ["Madhya Pradesh", "Chhattisgarh"],
}
SEGMENTS = ["Consumer", "Corporate", "Small Business"]
DISCOUNTS = [0.0, 0.0, 0.0, 0.05, 0.10, 0.10, 0.15, 0.20, 0.25, 0.30]

# Messy files use inconsistent header names on purpose.
HEADER_MAP = {
    "Order_ID": " order_id", "Order_Date": "ORDER DATE", "Customer_ID": "Customer Id",
    "Product": "product", "Category": "Category ", "Region": "region", "Quantity": "Qty",
    "Unit_Price": "Unit Price (INR)", "Sales": "Sales Amount", "Discount": "discount",
    "Profit": "Profit", "Sub_Category": "Sub Category", "Segment": "segment", "State": "STATE",
}


def build_truth(seed: int = SEED) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    days = pd.date_range(START, END, freq="D")
    w = np.where(days.month.isin(FESTIVE_MONTHS), FESTIVE_WEIGHT, 1.0)
    order_days = np.sort(rng.choice(days.values, size=N_ORDERS, p=w / w.sum()))

    customers = []
    for i in range(1, 201):
        region = list(REGIONS)[int(rng.integers(len(REGIONS)))]
        state = REGIONS[region][int(rng.integers(len(REGIONS[region])))]
        customers.append((f"C{i:04d}", region, state, SEGMENTS[int(rng.integers(3))]))

    rows = []
    for o, day in enumerate(order_days, start=1):
        day = pd.Timestamp(day)
        cid, region, state, segment = customers[int(rng.integers(len(customers)))]
        n_lines = int(rng.integers(1, 5))
        for p_idx in rng.choice(len(PRODUCTS), size=n_lines, replace=False):
            name, cat, sub, price, margin = PRODUCTS[int(p_idx)]
            # Planted story: North Electronics loses ~30% of lines in March 2026
            if (region == DROP["region"] and cat == DROP["category"]
                    and day.strftime("%Y-%m") == DROP["month"] and rng.random() < DROP["share_removed"]):
                continue
            qty = int(rng.integers(1, 21 if cat == "Office Supplies" else 4))
            disc = float(DISCOUNTS[int(rng.integers(len(DISCOUNTS)))])
            sales = round(qty * price * (1 - disc), 2)
            profit = round(sales * (margin + rng.normal(0, 0.03)) - qty * price * disc * 0.5, 2)
            if rng.random() < RETURN_RATE:   # a return: negative quantity, sales and profit
                qty, sales, profit = -qty, -sales, -abs(profit)
            rows.append({
                "Order_ID": f"IN-{day.year}-{o:06d}", "Order_Date": day, "Customer_ID": cid,
                "Product": name, "Category": cat, "Region": region, "Quantity": qty,
                "Unit_Price": float(price), "Sales": sales, "Discount": disc, "Profit": profit,
                "Sub_Category": sub, "Segment": segment, "State": state,
            })
    t = pd.DataFrame(rows)
    t.insert(0, "source_row_id", range(1, len(t) + 1))
    return t[COLUMNS]


def build(out_dir: Path) -> dict:
    truth = build_truth()
    messy, issues = make_messy(truth, LOCALE, SEED)
    return write_outputs(
        out_dir, DATASET_ID, truth, messy, issues,
        locale=LOCALE, header_map=HEADER_MAP, csv_encoding="utf-8-sig", csv_sep=";",
        source={"name": "Generated by scripts.sample_data.india", "seed": SEED},
        natural_issues=[],
        stories=[
            {"story": "festive_boost", "months": list(FESTIVE_MONTHS), "order_weight": FESTIVE_WEIGHT,
             "detail": "October-November (Diwali season) get 1.6x the orders"},
            {"story": "planted_drop", **DROP,
             "detail": "North-region Electronics loses ~30% of order lines in March 2026"},
            {"story": "returns", "rate": RETURN_RATE,
             "detail": "~2% of lines are returns: negative Quantity, Sales and Profit (valid, not errors)"},
            {"story": "line_items", "detail": "Order_ID repeats across lines of the same order (valid)"},
        ],
    )
